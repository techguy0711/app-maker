#!/usr/bin/env node
/**
 * gen-visual-tests.mjs — write one visual check per screen, from app-map.json.
 *
 * The agent never hand-writes these. Screens come and go as the user changes
 * their mind; regenerating from the map means the checks always match the app
 * that actually exists, with no stale test files to reconcile.
 *
 * Screens only, deliberately: an expo-router screen is a default export that
 * takes no props, so it can always be rendered blind. Arbitrary components
 * can require props that cannot be inferred without full type analysis, and a
 * test that renders a component with missing props fails for reasons that
 * have nothing to do with layout. Components are still covered — the screens
 * that use them render them.
 *
 * Usage:  node gen-visual-tests.mjs [projectDir]
 * Exit:   0 wrote tests | 3 no map | 4 no screens
 */

import fs from 'node:fs';
import path from 'node:path';

const projectDir = path.resolve(process.argv[2] || process.cwd());
const mapPath = path.join(projectDir, '.claude', 'app-map.json');

if (!fs.existsSync(mapPath)) {
  console.error('gen-visual-tests: no .claude/app-map.json — run app-map.mjs first');
  process.exit(3);
}
const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
const testDir = path.join(projectDir, '.claude', 'visual', 'tests');
fs.mkdirSync(testDir, { recursive: true });

// Remove only the generated test files, so a screen the user deleted stops
// being checked. Emphatically NOT the whole directory: Vitest keeps reference
// screenshots in `__screenshots__/` alongside the tests, and wiping those
// every run silently destroys the baseline — screenshots get recreated from
// the current render each time, so they always match and regression testing
// never fires at all. Caught by planting a visible layout change and watching
// the comparison pass anyway.
for (const f of fs.readdirSync(testDir)) {
  if (f.endsWith('.visual.test.tsx')) fs.rmSync(path.join(testDir, f), { force: true });
}

if (!map.screens?.length) {
  console.error('gen-visual-tests: no screens in map');
  process.exit(4);
}

const baseSlug = (route) => (route === '/' ? 'root' : route.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase());
// Every non-alphanumeric run collapses to '-', so `/settings/profile` and
// `/settings-profile` (also `/a_b` vs `/a-b`, `/(tabs)/x` vs `/tabs/x`) produced
// the SAME filename: the second write silently overwrote the first while the
// counter still reported both. One screen lost its safety net and the log said
// it had one. Disambiguate on collision rather than clobbering.
const usedSlugs = new Map();
const slug = (route) => {
  const base = baseSlug(route);
  if (!usedSlugs.has(base)) { usedSlugs.set(base, route); return base; }
  if (usedSlugs.get(base) === route) return base;
  let n = 2;
  while (usedSlugs.has(`${base}-${n}`)) n += 1;
  const unique = `${base}-${n}`;
  usedSlugs.set(unique, route);
  return unique;
};

let written = 0;
for (const screen of map.screens) {
  // Skipped, not silently passed: a screen built out of native-only controls
  // renders as placeholder boxes on web, so a screenshot of it would be
  // meaningless and its "layout" would be the stubs' layout, not the app's.
  if (screen.usesExpoUi) continue;

  const name = slug(screen.route);
  const importPath = path.relative(testDir, path.join(projectDir, screen.file))
    .replace(/\\/g, '/')
    .replace(/\.(tsx|ts|jsx|js)$/, '');

  fs.writeFileSync(path.join(testDir, `${name}.visual.test.tsx`), `\
// AUTO-GENERATED by scripts/gen-visual-tests.mjs — edits are lost on regen.
// Screen: ${screen.route}  (${screen.file})
import * as React from 'react';
import { expect, test } from 'vitest';
import { page } from 'vitest/browser';
import { render } from 'vitest-browser-react';
import { expectSaneLayout } from '../layout-checks';
import Screen from '${importPath}';

// A phone-sized host. Without a parent that has real dimensions, every
// \`flex: 1\` root collapses to zero height and every check reports a blank
// screen — a false failure on a perfectly good layout.
function Frame({ children }: { children: React.ReactNode }) {
  return (
    <div
      data-testid="visual-root"
      style={{ width: 390, height: 844, display: 'flex', flexDirection: 'column', overflow: 'hidden' }}
    >
      {children}
    </div>
  );
}

test('${screen.route} — layout is structurally sound', async () => {
  render(<Frame><Screen /></Frame>);

  // React 19 renders concurrently, so \`render()\` returns before anything is
  // in the DOM. Reading geometry straight afterwards measures an empty
  // container and every check reports a blank screen. Awaiting the locator
  // is what forces the flush — confirmed by dumping document.body right
  // after render: just \`<div data-testid="__vitest_N__"></div>\`.
  const rootLocator = page.getByTestId('visual-root');
  await expect.element(rootLocator).toBeVisible();
  const root = rootLocator.element() as HTMLElement;

  // Geometry assertions first. These need no baseline, so they are the only
  // thing protecting version 1 of an app, and their failures name the exact
  // element and the exact number of pixels involved.
  expectSaneLayout(root, '${screen.file}');

  // Then the regression guard. On the very first run no reference exists and
  // Vitest writes one and fails by design; ui-validate.sh treats that first
  // failure as baseline seeding, not as a layout defect.
  await expect(rootLocator).toMatchScreenshot('${name}');
});
`);
  written++;
}

const skipped = map.screens.filter(s => s.usesExpoUi).map(s => s.route);
console.log(`gen-visual-tests: ${written} test(s)` +
  (skipped.length ? ` (skipped native-UI screens: ${skipped.join(', ')})` : ''));

// Zero tests written is the same situation as zero screens, and must exit the
// same way. The guard at the top only covers an empty map, so an app whose
// every screen uses @expo/ui fell through here with exit 0 — and ui-validate.sh
// only treats exit 4 as "nothing to check". It then ran vitest against an
// include glob matching nothing, which cannot pass, and reported blocked-infra:
// the agent goes off diagnosing broken infrastructure for a project where there
// was simply nothing to check. Not hypothetical — phase-2-scaffold.md actively
// encourages building screens with expo:expo-ui.
if (written === 0) process.exit(4);
